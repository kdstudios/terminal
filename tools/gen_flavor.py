# ---- python-side expansion, for checking quality / counting -------------
SLOT = re.compile(r'\{([a-zA-Z_]+)(\^?)\}')


def fill(t, r, slots, d=0):
    def sub(m):
        b = slots.get(m.group(1))
        if b is None: return m.group(0)
        v = r.choice(b)
        if d < 3: v = fill(v, r, slots, d + 1)
        return v[0].upper() + v[1:] if m.group(2) == '^' and v else v
    return SLOT.sub(sub, t)


def count(t, slots, d=0):
    n = 1
    for m in SLOT.finditer(t):
        b = slots.get(m.group(1))
        if b is None: continue
        n *= sum(count(x, slots, d + 1) if d < 3 else 1 for x in b)
    return n



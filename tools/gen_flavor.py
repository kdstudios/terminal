def dq(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'


def dlist(name, items, indent='  '):
    body = ',\n'.join(f'{indent}  {dq(x)}' for x in items)
    return f'{indent}static const {name} = <String>[\n{body},\n{indent}];\n'


def dmap(name, m, indent='  '):
    inner = ',\n'.join(f"{indent}  '{k}': <String>[\n" + ',\n'.join(f'{indent}    {dq(x)}' for x in v) + f',\n{indent}  ]' for k, v in m.items())
    return f'{indent}static const {name} = <String, List<String>>{{\n{inner},\n{indent}}};\n'


